import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { solveBonusMasks } from "../src/level-validator.js";
import { LEVELS } from "../src/levels.js";
import { bonusObjectives } from "../src/rating.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src/levels/bonus-par.js");
const data = LEVELS.map((level) => {
  const result = solveBonusMasks(level);
  const fullMask = (2 ** bonusObjectives(level).length) - 1;
  if (result.truncated || !result.standardSolution || result.optimalDashesByBonusMask[fullMask] == null) {
    throw new Error(`Level ${level.id} bonus search failed (${result.explored} states)`);
  }
  return { optimalDashesByBonusMask: result.optimalDashesByBonusMask };
});

await writeFile(output, `// Generated by tools/generate-bonus-par.mjs. Do not edit.\nexport default ${JSON.stringify(data)};\n`, "utf8");
console.log(`Generated bonus pars for ${data.length} levels.`);
